CREATE DATABASE IF NOT EXISTS project_management CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE project_management;
CREATE TABLE IF NOT EXISTS users (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS projects (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(150) NOT NULL, description TEXT,
 deadline DATE NULL, owner_id INT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS tasks (
 id INT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(150) NOT NULL, description TEXT,
 status ENUM('Pending','In Progress','Completed') NOT NULL DEFAULT 'Pending',
 priority ENUM('Low','Medium','High') NOT NULL DEFAULT 'Medium', due_date DATE NULL,
 project_id INT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);
